import "server-only";
import { Workbook } from "exceljs";
import { query } from "@/lib/db";
import { addReportSheet, type ReportSheet } from "@/lib/reports/workbook";
import { excelDateTime } from "@/lib/reports/sql";
import type { SessionPayload } from "@/lib/session";

// The Staff directory's Excel export: every company_staff_data record,
// deactivated ones included with their status, for hr-advance holders.
// Logged to report_downloads like the Reports page's downloads; it has no
// date range, so the row records the day it was taken as both bounds.

export const STAFF_EXPORT_REPORT_TYPE = "staff-directory";

const STAFF_SHEET: Omit<ReportSheet, "rows"> = {
  name: "Staff",
  columns: [
    { key: "staffNumber", header: "Staff Number" },
    { key: "name", header: "Name" },
    { key: "email", header: "Email", kind: "text" },
    { key: "department", header: "Department" },
    { key: "location", header: "Location" },
    { key: "status", header: "Status" },
    { key: "deactivatedAt", header: "Deactivated At", kind: "datetime" },
    { key: "deactivatedBy", header: "Deactivated By" },
    {
      key: "deactivationReason",
      header: "Deactivation Reason",
      kind: "longtext",
    },
  ],
};

export async function buildStaffDirectoryExport(actor: SessionPayload) {
  const [rows, [{ today }]] = await Promise.all([
    query<Record<string, unknown>>(
      `SELECT staff_number AS "staffNumber", staff_name AS name,
       staff_email AS email, staff_department AS department,
       staff_location AS location,
       CASE WHEN deactivated_at IS NULL THEN 'Active' ELSE 'Deactivated' END AS status,
       ${excelDateTime("deactivated_at")} AS "deactivatedAt",
       deactivated_by AS "deactivatedBy",
       deactivation_reason AS "deactivationReason"
       FROM company_staff_data
       ORDER BY staff_name, staff_number`,
    ),
    query<{ today: string }>(
      `SELECT TO_CHAR((NOW() AT TIME ZONE 'Africa/Nairobi')::date, 'YYYY-MM-DD') AS today`,
    ),
  ]);

  const workbook = new Workbook();
  workbook.creator = "Hotpoint Apps Hub";
  workbook.created = new Date();
  addReportSheet(workbook, { ...STAFF_SHEET, rows });

  const active = rows.filter((row) => row.status === "Active").length;
  const info = workbook.addWorksheet("Export Info");
  info.columns = [{ width: 24 }, { width: 60 }];
  info.addRows([
    ["Export", "Staff directory (salary advance)"],
    ["Records", String(rows.length)],
    ["Active", String(active)],
    ["Deactivated", String(rows.length - active)],
    ["Generated by", `${actor.name} (${actor.email})`],
    [
      "Generated at",
      `${new Date().toLocaleString("en-GB", {
        day: "2-digit",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        timeZone: "Africa/Nairobi",
      })} (Africa/Nairobi)`,
    ],
    [
      "Note",
      "Staff records are imported from the HR system; this is the copy the Apps Hub uses for salary advance verification.",
    ],
  ]);
  info.getColumn(1).font = { bold: true };

  return {
    buffer: await workbook.xlsx.writeBuffer(),
    rowCount: rows.length,
    today,
  };
}
